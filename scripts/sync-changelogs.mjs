#!/usr/bin/env node
/**
 * sync-changelogs.mjs — generate the docs Changelog pages from each package's
 * own CHANGELOG.md.
 *
 * The docs deploy as a standalone repo, so the generated `.md` files are
 * COMMITTED (CI never sees the sibling packages). Re-run this locally after a
 * release to refresh:  npm run sync:changelogs
 *
 * Missing sources are skipped with a warning and any existing generated page is
 * left untouched, so running this anywhere (incl. CI) is a safe no-op.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DOCS_ROOT = resolve(__dirname, '..');
// All waveform repos are flat siblings of this one under ~/Developer/Javascript/waveform-player.
const PKG_ROOT = resolve(DOCS_ROOT, '..');
const OUT_DIR = join(DOCS_ROOT, 'src/content/docs/changelog');

const GENERATED = '<!-- GENERATED by scripts/sync-changelogs.mjs — do not edit by hand. -->';

const read = (pkg) => {
	const p = join(PKG_ROOT, pkg, 'CHANGELOG.md');
	return existsSync(p) ? readFileSync(p, 'utf8') : null;
};

/** Drop the leading "# Changelog" H1 + intro prose; keep from the first `## ` entry. */
const entries = (md) => {
	const i = md.search(/^## /m);
	return (i === -1 ? md : md.slice(i)).trim();
};

/** Demote ATX headings by `levels`, leaving fenced code blocks alone. */
const demote = (md, levels) => {
	let fence = false;
	return md
		.split('\n')
		.map((line) => {
			if (/^\s*```/.test(line)) fence = !fence;
			const m = !fence && line.match(/^(#{1,6})(\s)/);
			return m ? '#'.repeat(Math.min(6, m[1].length + levels)) + line.slice(m[1].length) : line;
		})
		.join('\n');
};

const frontmatter = ({ title, description, order }) =>
	`---\ntitle: ${title}\ndescription: ${description}\nsidebar:\n  order: ${order}\n---\n`;

// `repo` is the bare GitHub repo name (e.g. `waveform-player`); the npm package
// is the scoped `@arraypress/<repo>`.
const sourceNote = (repo) =>
	`:::note\nGenerated from [\`@arraypress/${repo}\`'s CHANGELOG](https://github.com/WaveformPlayer/${repo}/blob/main/CHANGELOG.md). Run \`npm run sync:changelogs\` after a release to refresh.\n:::`;

function write(slug, contents) {
	mkdirSync(OUT_DIR, { recursive: true });
	writeFileSync(join(OUT_DIR, `${slug}.md`), contents.replace(/\n*$/, '\n'));
	console.log(`  ✓ changelog/${slug}.md`);
}

// ── Single-package pages ────────────────────────────────────────────────────
const SINGLE = [
	{ slug: 'player', pkg: 'waveform-player', title: 'Core Player', order: 1, description: 'Release history for @arraypress/waveform-player.' },
	{ slug: 'bar', pkg: 'waveform-bar', title: 'Bar', order: 2, description: 'Release history for @arraypress/waveform-bar.' },
	{ slug: 'playlist', pkg: 'waveform-playlist', title: 'Playlist', order: 3, description: 'Release history for @arraypress/waveform-playlist.' },
	{
		slug: 'sounds', pkg: 'waveform-sounds', title: 'Sounds', order: 4, description: 'Release history for @arraypress/waveform-sounds.',
		// Its components live on the framework packages page, like every other component.
		see: 'The Astro, React, Svelte and Vue components are the `/sounds` sub-path of each framework package and version with it — see [Framework packages](/changelog/frameworks/). Before 2.0 they were separate wrappers — see [Framework wrappers (1.x)](/changelog/frameworks-1x/#arraypresswaveform-sounds-astro).',
	},
	{ slug: 'gen', pkg: 'waveform-gen', title: 'Generator', order: 5, description: 'Release history for @arraypress/waveform-gen.' },
	{ slug: 'tracker', pkg: 'waveform-tracker', title: 'Tracker', order: 6, description: 'Release history for @arraypress/waveform-tracker.' },
];

for (const { slug, pkg, title, order, description, see } of SINGLE) {
	const md = read(pkg);
	if (!md) {
		console.warn(`  ⚠ ${pkg}/CHANGELOG.md not found — leaving changelog/${slug}.md as-is.`);
		continue;
	}
	write(slug, [frontmatter({ title, description, order }), GENERATED, '', sourceNote(pkg), '', ...(see ? [see, ''] : []), entries(md)].join('\n'));
}

// ── Framework packages (2.0+): one repo per framework ──────────────────────
// `dir` is the sibling repo; each publishes `@arraypress/waveform-<dir>` with
// /player /bar /playlist /sounds sub-paths.
const FRAMEWORKS = ['react', 'vue', 'svelte', 'astro'];

const frameworkSections = FRAMEWORKS.map((dir) => {
	const md = read(dir);
	if (!md) {
		console.warn(`  ⚠ ${dir}/CHANGELOG.md not found — omitting from frameworks page.`);
		return null;
	}
	return `## \`@arraypress/waveform-${dir}\`\n\n${demote(entries(md), 1)}`;
}).filter(Boolean);

if (frameworkSections.length) {
	write('frameworks', [
		frontmatter({ title: 'Framework packages', description: 'Release history for @arraypress/waveform-react, -vue, -svelte and -astro.', order: 7 }),
		GENERATED,
		'',
		':::note\nGenerated from each framework package\'s CHANGELOG. Run `npm run sync:changelogs` after a release to refresh.\n:::',
		'',
		'One package per framework since 2.0, each with `/player`, `/bar`, `/playlist` and `/sounds` sub-paths. The sixteen single-component packages they replace are on [Framework wrappers (1.x)](/changelog/frameworks-1x/).',
		'',
		frameworkSections.join('\n\n'),
	].join('\n'));
}

// ── Historical "Framework wrappers (1.x)" page ──────────────────────────────
// The sixteen single-component wrappers, deprecated by the packages above.
const WRAPPERS = [
	'waveform-player-astro',
	'waveform-player-react',
	'waveform-player-vue',
	'waveform-player-svelte',
	'waveform-bar-astro',
	'waveform-bar-react',
	'waveform-bar-vue',
	'waveform-bar-svelte',
	'waveform-playlist-astro',
	'waveform-playlist-react',
	'waveform-playlist-vue',
	'waveform-playlist-svelte',
	'waveform-sounds-astro',
	'waveform-sounds-react',
	'waveform-sounds-vue',
	'waveform-sounds-svelte',
];

const sections = WRAPPERS.map((pkg) => {
	const md = read(pkg);
	if (!md) {
		console.warn(`  ⚠ ${pkg}/CHANGELOG.md not found — omitting from frameworks page.`);
		return null;
	}
	// Demote so each package's `## [x.y.z]` sits under a `## @arraypress/<pkg>` h2.
	return `## \`@arraypress/${pkg}\`\n\n${demote(entries(md), 1)}`;
}).filter(Boolean);

if (sections.length) {
	write('frameworks-1x', [
		frontmatter({ title: 'Framework wrappers (1.x)', description: 'Release history for the sixteen 1.x Astro, React, Vue and Svelte wrapper packages, replaced in 2.0.', order: 8 }),
		GENERATED,
		'',
		':::note\nGenerated from each wrapper package\'s CHANGELOG. Run `npm run sync:changelogs` after a release to refresh.\n:::',
		'',
		'These single-component wrappers served the 1.x cores and are deprecated. In 2.0 they are replaced by one package per framework — see [Framework packages](/changelog/frameworks/) and [Migrating from 1.x](/getting-started/migrating-from-1x/#package-names).',
		'',
		sections.join('\n\n'),
	].join('\n'));
}

console.log('Changelog sync complete.');
